// Generates supabase/migrations/115_round_off_cash_discount.sql (+ down + preview) FROM the code's own
// ACCOUNTS_TO_ADD_115 list (src/lib/storage.ts), so the SQL can never drift from what the app merges on screen.
//   node scripts/gen-migration-115.mjs          → writes the three files
// test:migration-115 re-runs buildFiles() and fails if a committed file differs.
import { register } from 'node:module';
import { writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(ROOT, 'src');
register('data:text/javascript,' + encodeURIComponent(`
  import { existsSync } from 'node:fs';
  import { fileURLToPath, pathToFileURL } from 'node:url';
  import { resolve as PR } from 'node:path';
  const SRC = ${JSON.stringify(SRC)};
  export async function resolve(spec, ctx, next) {
    if (spec.startsWith('@/')) { const b = PR(SRC, spec.slice(2)); for (const q of [b + '.ts', b + '.tsx', b + '/index.ts', b]) if (existsSync(q)) return { url: pathToFileURL(q).href, shortCircuit: true }; }
    if (spec.startsWith('.') && !/\\.(ts|tsx|js|mjs|json)$/.test(spec)) { for (const q of [spec + '.ts', spec + '/index.ts']) { const u = new URL(q, ctx.parentURL); if (existsSync(fileURLToPath(u))) return { url: u.href, shortCircuit: true }; } }
    return next(spec, ctx);
  }
`));
const S = await import(pathToFileURL(path.join(SRC, 'lib/storage.ts')).href);

const q = (v) => (v == null ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const b = (v) => (v ? 'true' : 'false');

export function valuesBlock() {
  return S.ACCOUNTS_TO_ADD_115.map((a, i) =>
    `    (${q(a.id)}, ${q(a.name)}, ${q(a.nameHi)}, ${q(a.type)}, ${q(a.openingBalanceType)}, ${b(a.isSystem)}, ${b(a.isGroup)}, ${q(a.parentId)}, ${q(a.subtype)}, ${i})`
  ).join(',\n');
}

// Same rule as storage.migrateAccounts: skip when the id exists OR the same name+type exists; and (database
// rule) the parent must exist. Extra: skip when another account already SHOWS this code (accounts.code, #706),
// so no society ends up with two accounts displaying the same code.
const missing = `
  from (select distinct society_id from public.accounts) s
 cross join (values
${valuesBlock()}
  ) as v(id, name, "nameHi", type, "openingBalanceType", "isSystem", "isGroup", "parentId", subtype, ord)
 where not exists (select 1 from public.accounts a where a.society_id = s.society_id and a.id = v.id)
   and not exists (select 1 from public.accounts a where a.society_id = s.society_id and a.code = v.id)
   and not exists (select 1 from public.accounts a where a.society_id = s.society_id and lower(trim(a.name)) = lower(trim(v.name)) and a.type = v.type)
   and exists (select 1 from public.accounts p where p.society_id = s.society_id and p.id = v."parentId")`;

export function buildFiles() {
  const migration = `-- 115 · Round off (sales + purchases) and cash discount (purchases): 3 columns + 2 accounts.
-- GENERATED by scripts/gen-migration-115.mjs from the code's own ACCOUNTS_TO_ADD_115 list — do not edit by hand.
--
-- WHY: a sale can now be rounded to the rupee, and a purchase bill can carry a cash discount AFTER GST (GST / ITC
-- unchanged) plus a round off. The amounts are stored on the bill (step-2 extras, RULE 1) and posted to two new
-- accounts — 4499 Discount Received (other income) and 5499 Round Off (indirect expense) — which the app merges on
-- screen for every society; this persists them so the server accepts the first voucher on them.
--
-- WHAT: (1) add the columns sales."roundOff", purchases."cashDiscount", purchases."roundOff" (numeric default 0);
-- (2) for every society, add each account it lacks — skip when the id exists, when another account already shows
-- that code, or when an account with the same name and type exists; only where the parent group exists.
-- Opening balance 0. INSERT only, "on conflict do nothing": no existing row is changed or removed.
-- Run supabase/diagnostics/preview_115_round_off_cash_discount.sql first. Undo: 115_..._down.sql.
-- NO temp tables — the SQL Editor's "Run and enable RLS" splits statements.

begin;

alter table public.sales     add column if not exists "roundOff"     numeric default 0;
alter table public.purchases add column if not exists "cashDiscount" numeric default 0;
alter table public.purchases add column if not exists "roundOff"     numeric default 0;

insert into public.accounts (id, society_id, name, "nameHi", type, "openingBalance", "openingBalanceType", "isSystem", "isGroup", "parentId", subtype, jurisdiction)
select v.id, s.society_id, v.name, v."nameHi", v.type, 0, v."openingBalanceType", v."isSystem", v."isGroup", v."parentId", v.subtype,
       (select a.jurisdiction from public.accounts a where a.society_id = s.society_id and a.jurisdiction is not null limit 1)${missing}
on conflict do nothing;

insert into public.app_migrations (version, name) values ('115', 'round_off_cash_discount')
  on conflict (version) do nothing;

commit;

notify pgrst, 'reload schema';
`;

  const preview = `-- preview for 115 · READ-ONLY. GENERATED by scripts/gen-migration-115.mjs. Run BEFORE migration 115.
-- One row per account migration 115 will add, per society. Nothing is written. (Expected on 2026-10-08: 62 rows = 31 × 2.)
select s.society_id, v.id as account_id, v.name${missing}
 order by s.society_id, v.ord;
`;

  const down = `-- 115 down · remove ONLY the accounts migration 115 added (where nothing references them) and the 3 columns.
-- Run only if no bill has used them yet: dropping the columns loses any stored round off / cash discount.
begin;
delete from public.accounts a
 where a.id in (${S.ACCOUNTS_TO_ADD_115.map((x) => q(x.id)).join(', ')})
   and coalesce(a."openingBalance", 0) = 0
   and not exists (select 1 from public.voucher_lines l where l.society_id::text = a.society_id::text and l.account_id = a.id)
   and not exists (select 1 from public.voucher_entries l where l.society_id::text = a.society_id::text and l."accountId" = a.id)
   and not exists (select 1 from public.account_roles r where r.society_id::text = a.society_id::text and r.account_id = a.id);
alter table public.sales     drop column if exists "roundOff";
alter table public.purchases drop column if exists "cashDiscount";
alter table public.purchases drop column if exists "roundOff";
delete from public.app_migrations where version = '115';
commit;
notify pgrst, 'reload schema';
`;
  return {
    'supabase/migrations/115_round_off_cash_discount.sql': migration,
    'supabase/migrations/115_round_off_cash_discount_down.sql': down,
    'supabase/diagnostics/preview_115_round_off_cash_discount.sql': preview,
  };
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  for (const [f, text] of Object.entries(buildFiles())) { writeFileSync(path.join(ROOT, f), text, 'utf8'); console.log('wrote', f); }
}
