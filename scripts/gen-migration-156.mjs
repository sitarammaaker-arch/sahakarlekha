// Generates supabase/migrations/156_gst_headwise_ledgers.sql (+ down + preview) FROM the code's own
// ACCOUNTS_TO_ADD_156 list (src/lib/storage.ts), so the SQL can never drift from what the app merges on screen.
//   node scripts/gen-migration-156.mjs          → writes the three files
// test:migration-156 re-runs buildFiles() and fails if a committed file differs.
import { register } from 'node:module';
import { writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(ROOT, 'src');
register('data:text/javascript,' + encodeURIComponent(`
  import { existsSync } from 'node:fs';
  import { fileURLToPath, pathToFileURL } from 'node:url';
  import { resolve as PR } from 'node:path';
  const SRC = ${JSON.stringify(SRC)};
  export async function resolve(spec, ctx, next) {
    if (spec.startsWith('@/')) { const b = PR(SRC, spec.slice(2)); for (const q of [b + '.ts', b + '.tsx', b + '/index.ts', b]) if (existsSync(q)) return { url: pathToFileURL(q).href, shortCircuit: true }; }
    if (spec.startsWith('.') && !/\\.(ts|tsx|js|mjs|json)$/.test(spec)) { for (const q of [spec + '.ts', spec + '/index.ts']) { const u = new URL(q, ctx.parentURL); if (existsSync(fileURLToPath(u))) return { url: u.href, shortCircuit: true }; } }
    return next(spec, ctx);
  }
`));
const S = await import(pathToFileURL(path.join(SRC, 'lib/storage.ts')).href);

const q = (v) => (v == null ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const b = (v) => (v ? 'true' : 'false');


// One VALUES row per account.
export function valuesBlock() {
  return S.ACCOUNTS_TO_ADD_156.map((a, i) =>
    `    (${q(a.id)}, ${q(a.name)}, ${q(a.nameHi)}, ${q(a.type)}, ${q(a.openingBalanceType)}, ${b(a.isSystem)}, ${b(a.isGroup)}, ${q(a.parentId)}, ${q(a.subtype)}, ${i})`).join(',\n');
}

// Same rule as storage.migrateAccounts: skip when the id exists OR the same name+type exists; and (database
// rule) the parent must exist. Extra: skip when another account already SHOWS this code (accounts.code, #706).
const missing = `
  from (select distinct society_id from public.accounts) s
 cross join (values
${valuesBlock()}
  ) as v(id, name, "nameHi", type, "openingBalanceType", "isSystem", "isGroup", "parentId", subtype, ord)
 where not exists (select 1 from public.accounts a where a.society_id = s.society_id and a.id = v.id)
   and not exists (select 1 from public.accounts a where a.society_id = s.society_id and a.code = v.id)
   and not exists (select 1 from public.accounts a where a.society_id = s.society_id and lower(trim(a.name)) = lower(trim(v.name)) and a.type = v.type)
   and exists (select 1 from public.accounts p where p.society_id = s.society_id and p.id = v."parentId")`;

export function buildFiles() {
  const migration = `-- 156 · Head-wise GST ledgers: Output CGST / SGST / IGST and Input CGST / SGST / IGST.
-- GENERATED by scripts/gen-migration-156.mjs from the code's own ACCOUNTS_TO_ADD_156 list — do not edit by hand.
--
-- WHY: all GST was posted to one "GST Payable" (2201) and one "GST Input Credit" (3310). Credit of central tax
-- cannot be set off against State tax or the reverse (CGST Act s.49(5)), and the accounts must show output tax
-- and input credit separately (s.35; CGST Rules r.56). The app now posts NEW bills head-wise — but only to heads
-- the database holds, so this must run BEFORE the app update is merged; until then the app keeps using 2201 / 3310.
--
-- WHAT: for every society, add each of the six accounts it lacks — skip when the id exists, when another account
-- already shows that code, or when an account with the same name and type exists; only where the parent group
-- (2200 / 3300) exists. Opening balance 0. INSERT only, "on conflict do nothing": 2201 and 3310, their balances
-- and every posted voucher are untouched, so no report figure changes.
-- Run supabase/diagnostics/preview_156_gst_headwise_ledgers.sql first. Undo: 156_..._down.sql.
-- NO temp tables — the SQL Editor's "Run and enable RLS" splits statements.

begin;

insert into public.accounts (id, society_id, name, "nameHi", type, "openingBalance", "openingBalanceType", "isSystem", "isGroup", "parentId", subtype, jurisdiction)
select v.id, s.society_id, v.name, v."nameHi", v.type, 0, v."openingBalanceType", v."isSystem", v."isGroup", v."parentId", v.subtype,
       (select a.jurisdiction from public.accounts a where a.society_id = s.society_id and a.jurisdiction is not null limit 1)${missing}
on conflict do nothing;

insert into public.app_migrations (version, name) values ('156', 'gst_headwise_ledgers')
  on conflict (version) do nothing;

commit;

notify pgrst, 'reload schema';
`;

  const preview = `-- preview for 156 · READ-ONLY. GENERATED by scripts/gen-migration-156.mjs. Run BEFORE migration 156.
-- One row per account migration 156 will add, per society. Nothing is written.
select s.society_id, v.id as account_id, v.name${missing}
 order by s.society_id, v.ord;
`;

  const down = `-- 156 down · remove ONLY the accounts migration 156 added, where nothing references them.
begin;
delete from public.accounts a
 where a.id in (${S.ACCOUNTS_TO_ADD_156.map((x) => q(x.id)).join(', ')})
   and a.name in (${S.ACCOUNTS_TO_ADD_156.map((x) => q(x.name)).join(', ')})
   and coalesce(a."openingBalance", 0) = 0
   and not exists (select 1 from public.voucher_lines l where l.society_id::text = a.society_id::text and l.account_id = a.id)
   and not exists (select 1 from public.voucher_entries l where l.society_id::text = a.society_id::text and l."accountId" = a.id)
   and not exists (select 1 from public.account_roles r where r.society_id::text = a.society_id::text and r.account_id = a.id);
delete from public.app_migrations where version = '156';
commit;
notify pgrst, 'reload schema';
`;
  return {
    'supabase/migrations/156_gst_headwise_ledgers.sql': migration,
    'supabase/migrations/156_gst_headwise_ledgers_down.sql': down,
    'supabase/diagnostics/preview_156_gst_headwise_ledgers.sql': preview,
  };
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  for (const [f, text] of Object.entries(buildFiles())) { writeFileSync(path.join(ROOT, f), text, 'utf8'); console.log('wrote', f); }
}
