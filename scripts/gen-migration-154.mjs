// Generates supabase/migrations/154_statutory_payable_heads.sql (+ down + preview) FROM the code's own
// ACCOUNTS_TO_ADD_154 list (src/lib/storage.ts), so the SQL can never drift from what the app merges on screen.
//   node scripts/gen-migration-154.mjs          → writes the three files
// test:migration-154 re-runs buildFiles() and fails if a committed file differs.
import { register } from 'node:module';
import { writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(ROOT, 'src');
register('data:text/javascript,' + encodeURIComponent(`
  import { existsSync } from 'node:fs';
  import { fileURLToPath, pathToFileURL } from 'node:url';
  import { resolve as PR } from 'node:path';
  const SRC = ${JSON.stringify(SRC)};
  export async function resolve(spec, ctx, next) {
    if (spec.startsWith('@/')) { const b = PR(SRC, spec.slice(2)); for (const q of [b + '.ts', b + '.tsx', b + '/index.ts', b]) if (existsSync(q)) return { url: pathToFileURL(q).href, shortCircuit: true }; }
    if (spec.startsWith('.') && !/\\.(ts|tsx|js|mjs|json)$/.test(spec)) { for (const q of [spec + '.ts', spec + '/index.ts']) { const u = new URL(q, ctx.parentURL); if (existsSync(fileURLToPath(u))) return { url: u.href, shortCircuit: true }; } }
    return next(spec, ctx);
  }
`));
const S = await import(pathToFileURL(path.join(SRC, 'lib/storage.ts')).href);

const q = (v) => (v == null ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const b = (v) => (v ? 'true' : 'false');


// One VALUES row per account. The last two columns carry the "only where this account exists" condition of
// ACCOUNTS_TO_ADD_154_REQUIRES (null = add to every society).
export function valuesBlock() {
  return S.ACCOUNTS_TO_ADD_154.map((a, i) => {
    const needs = S.ACCOUNTS_TO_ADD_154_REQUIRES[a.id];
    return `    (${q(a.id)}, ${q(a.name)}, ${q(a.nameHi)}, ${q(a.type)}, ${q(a.openingBalanceType)}, ${b(a.isSystem)}, ${b(a.isGroup)}, ${q(a.parentId)}, ${q(a.subtype)}, ${q(needs?.id)}, ${q(needs?.name)}, ${i})`;
  }).join(',\n');
}

// Same rule as storage.migrateAccounts: skip when the id exists OR the same name+type exists; a head with a
// "requires" condition only where that account (same id AND name) exists; and (database rule) the parent must
// exist. Extra: skip when another account already SHOWS this code (accounts.code, #706).
const missing = `
  from (select distinct society_id from public.accounts) s
 cross join (values
${valuesBlock()}
  ) as v(id, name, "nameHi", type, "openingBalanceType", "isSystem", "isGroup", "parentId", subtype, needs_id, needs_name, ord)
 where not exists (select 1 from public.accounts a where a.society_id = s.society_id and a.id = v.id)
   and not exists (select 1 from public.accounts a where a.society_id = s.society_id and a.code = v.id)
   and not exists (select 1 from public.accounts a where a.society_id = s.society_id and lower(trim(a.name)) = lower(trim(v.name)) and a.type = v.type)
   and (v.needs_id is null or exists (select 1 from public.accounts n where n.society_id = s.society_id and n.id = v.needs_id and lower(trim(n.name)) = lower(trim(v.needs_name))))
   and exists (select 1 from public.accounts p where p.society_id = s.society_id and p.id = v."parentId")`;

export function buildFiles() {
  const migration = `-- 154 · Payable heads the chart lacked: education fund, gratuity, bonus, market fee, GST reverse charge.
-- GENERATED by scripts/gen-migration-154.mjs from the code's own ACCOUNTS_TO_ADD_154 list — do not edit by hand.
--
-- WHY: the 2026-11-11 comparison of the standard charts with the official texts found five liabilities with no
-- head to hold them: the education fund share owed to the outside fund, the credit side of the gratuity and bonus
-- expense heads, market fee collected for the Market Committee, and GST payable on reverse charge. The app merges
-- these on screen for every society; this persists them so the server accepts the first voucher on them.
--
-- WHAT: for every society, add each account it lacks — skip when the id exists, when another account already
-- shows that code, or when an account with the same name and type exists; only where the parent group exists.
-- 2296 Market Fee Payable is added only to a society whose chart has the 4202 "Market Fee" head.
-- Opening balance 0. INSERT only, "on conflict do nothing": no existing row is changed or removed, so no report
-- figure changes. Run supabase/diagnostics/preview_154_statutory_payable_heads.sql first. Undo: 154_..._down.sql.
-- NO temp tables — the SQL Editor's "Run and enable RLS" splits statements.

begin;

insert into public.accounts (id, society_id, name, "nameHi", type, "openingBalance", "openingBalanceType", "isSystem", "isGroup", "parentId", subtype, jurisdiction)
select v.id, s.society_id, v.name, v."nameHi", v.type, 0, v."openingBalanceType", v."isSystem", v."isGroup", v."parentId", v.subtype,
       (select a.jurisdiction from public.accounts a where a.society_id = s.society_id and a.jurisdiction is not null limit 1)${missing}
on conflict do nothing;

insert into public.app_migrations (version, name) values ('154', 'statutory_payable_heads')
  on conflict (version) do nothing;

commit;

notify pgrst, 'reload schema';
`;

  const preview = `-- preview for 154 · READ-ONLY. GENERATED by scripts/gen-migration-154.mjs. Run BEFORE migration 154.
-- One row per account migration 154 will add, per society. Nothing is written.
select s.society_id, v.id as account_id, v.name${missing}
 order by s.society_id, v.ord;
`;

  const down = `-- 154 down · remove ONLY the accounts migration 154 added, where nothing references them.
begin;
delete from public.accounts a
 where a.id in (${S.ACCOUNTS_TO_ADD_154.map((x) => q(x.id)).join(', ')})
   and a.name in (${S.ACCOUNTS_TO_ADD_154.map((x) => q(x.name)).join(', ')})
   and coalesce(a."openingBalance", 0) = 0
   and not exists (select 1 from public.voucher_lines l where l.society_id::text = a.society_id::text and l.account_id = a.id)
   and not exists (select 1 from public.voucher_entries l where l.society_id::text = a.society_id::text and l."accountId" = a.id)
   and not exists (select 1 from public.account_roles r where r.society_id::text = a.society_id::text and r.account_id = a.id);
delete from public.app_migrations where version = '154';
commit;
notify pgrst, 'reload schema';
`;
  return {
    'supabase/migrations/154_statutory_payable_heads.sql': migration,
    'supabase/migrations/154_statutory_payable_heads_down.sql': down,
    'supabase/diagnostics/preview_154_statutory_payable_heads.sql': preview,
  };
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  for (const [f, text] of Object.entries(buildFiles())) { writeFileSync(path.join(ROOT, f), text, 'utf8'); console.log('wrote', f); }
}
