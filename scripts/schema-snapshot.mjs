// DB-01 (product audit 2026-11-17): "the schema cannot be rebuilt from the repository; no staging rebuild is provably
// equal to production". This keeps a committed, deterministic description of production's public schema:
// tables, columns, keys, checks, indexes, RLS policies, triggers, function signatures (+ body digest) and grants.
//
//   node scripts/schema-snapshot.mjs            # read production (read-only) → rewrite supabase/schema/production-schema.txt
//   node scripts/schema-snapshot.mjs --check    # read production and print what differs from the committed file (exit 1)
//   node scripts/schema-snapshot.mjs --check --db-url <url>   # the same against another database (e.g. a staging rebuild)
//
// The query (scripts/schema-snapshot.sql) runs inside `begin transaction read only … rollback`. Refresh the file after
// every migration you run, in the same PR — test:schema-snapshot pins the repo to it.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const SNAPSHOT = join(ROOT, 'supabase', 'schema', 'production-schema.txt');
const HEADER = [
  '# Production public schema — generated by scripts/schema-snapshot.mjs (DB-01). Do not edit by hand.',
  '# One object per line, sorted. Function bodies are digested (body_md5); their source is in supabase/migrations.',
];

/** Parse `supabase db query -o json` output: the JSON object sits between the first "{" and the last "}". */
export function parseQueryOutput(text) {
  const json = JSON.parse(text.slice(text.indexOf('{'), text.lastIndexOf('}') + 1));
  const lines = json.rows?.[0]?.r?.lines;
  if (!Array.isArray(lines) || lines.length === 0) throw new Error('schema query returned no lines');
  return [...new Set(lines.map((l) => String(l).replace(/\s+/g, ' ').trim()))].sort();
}

/** Lines that must never be committed (a key, a token or a password inside a default or a policy). */
export function findSecrets(lines) {
  return lines.filter((l) => /eyJ[A-Za-z0-9_-]{20,}|sk_live_|service_role_key|password\s*=\s*'|bearer\s+[A-Za-z0-9._-]{20,}/i.test(l));
}

export function diffLines(oldLines, newLines) {
  const a = new Set(oldLines), b = new Set(newLines);
  return { removed: oldLines.filter((l) => !b.has(l)), added: newLines.filter((l) => !a.has(l)) };
}

export function readSnapshot(file = SNAPSHOT) {
  return readFileSync(file, 'utf8').replace(/\r\n/g, '\n').split('\n').filter((l) => l && !l.startsWith('#'));
}

function queryLive(dbUrl) {
  const args = ['supabase', 'db', 'query', ...(dbUrl ? ['--db-url', dbUrl] : ['--linked']), '-f', join(ROOT, 'scripts', 'schema-snapshot.sql'), '-o', 'json'];
  const out = execFileSync('npx', args, { cwd: ROOT, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024, shell: process.platform === 'win32' });
  return parseQueryOutput(out);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  const check = process.argv.includes('--check');
  const urlAt = process.argv.indexOf('--db-url');
  const live = queryLive(urlAt > 0 ? process.argv[urlAt + 1] : undefined);
  const secrets = findSecrets(live);
  if (secrets.length) { console.error(`refusing: ${secrets.length} line(s) look like a secret — fix the schema first`); process.exit(2); }
  if (check) {
    if (!existsSync(SNAPSHOT)) { console.error('no committed snapshot yet'); process.exit(1); }
    const { removed, added } = diffLines(readSnapshot(), live);
    for (const l of removed) console.log(`- ${l}`);
    for (const l of added) console.log(`+ ${l}`);
    console.log(removed.length + added.length === 0 ? 'schema matches the committed snapshot' : `${removed.length} removed, ${added.length} added vs the committed snapshot`);
    process.exit(removed.length + added.length === 0 ? 0 : 1);
  }
  mkdirSync(dirname(SNAPSHOT), { recursive: true });
  writeFileSync(SNAPSHOT, [...HEADER, ...live, ''].join('\n'));
  console.log(`wrote ${live.length} lines → ${SNAPSHOT}`);
}
