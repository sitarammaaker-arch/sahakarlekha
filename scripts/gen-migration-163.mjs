// Generates supabase/migrations/163_rename_duplicate_named_heads.sql (+ down + preview) FROM the code's own
// ACCOUNT_RENAMES_163 list (src/lib/storage.ts), so the SQL can never drift from what
// the app shows on screen.
//   node scripts/gen-migration-163.mjs          → writes the three files
// test:migration-163 re-runs buildFiles() and fails if a committed file differs.
import { register } from 'node:module';
import { writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(ROOT, 'src');
register('data:text/javascript,' + encodeURIComponent(`
  import { existsSync } from 'node:fs';
  import { fileURLToPath, pathToFileURL } from 'node:url';
  import { resolve as PR } from 'node:path';
  const SRC = ${JSON.stringify(SRC)};
  export async function resolve(spec, ctx, next) {
    if (spec.startsWith('@/')) { const b = PR(SRC, spec.slice(2)); for (const q of [b + '.ts', b + '.tsx', b + '/index.ts', b]) if (existsSync(q)) return { url: pathToFileURL(q).href, shortCircuit: true }; }
    if (spec.startsWith('.') && !/\\.(ts|tsx|js|mjs|json)$/.test(spec)) { for (const q of [spec + '.ts', spec + '/index.ts']) { const u = new URL(q, ctx.parentURL); if (existsSync(fileURLToPath(u))) return { url: u.href, shortCircuit: true }; } }
    return next(spec, ctx);
  }
`));
const S = await import(pathToFileURL(path.join(SRC, 'lib/storage.ts')).href);


const q = (v) => (v == null ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const R = S.ACCOUNT_RENAMES_163;

// One row per rename. A head is renamed only while it still carries the OLD name and type, and only where no
// other ledger of that type in the same society already carries the NEW name (never create a duplicate).
export function valuesBlock() {
  return R.map((r, i) => `    (${q(r.id)}, ${q(r.from)}, ${q(r.type)}, ${q(r.to)}, ${i})`).join(',\n');
}
const targets = `
  from public.accounts a
  join (values
${valuesBlock()}
  ) as v(id, old_name, type, new_name, ord)
    on a.id = v.id and trim(a.name) = v.old_name and a.type = v.type
 where not exists (select 1 from public.accounts o
                    where o.society_id = a.society_id and o.type = a.type and o.id <> a.id
                      and lower(trim(o.name)) = lower(v.new_name))`;

export function buildFiles() {
  const migration = `-- 163 · Rename the standard-chart heads that shared a name with another ledger of the same chart.
-- GENERATED by scripts/gen-migration-163.mjs from the code's own ACCOUNT_RENAMES_163 list — do not edit by hand.
--
-- WHY: the standard charts shipped two or three ledgers under one name ("Building" the asset and "Building"
-- the depreciation head; "Rent" income and "Rent" expense; "Vehicle" three times; "Transport" twice). Anything
-- that finds a ledger by name could pick the wrong one. The app now shows the expense / income head under a name
-- that says what it is (storage.ts, on every load); this makes the database say the same.
--
-- WHAT: the NAME column only, of a row that still has the old name and type, and only where no other ledger of
-- that type in the society already carries the new name. NOT touched: id, type, parent, any amount, opening
-- balance, voucher, voucher line or ledger event — so no figure in any statement changes; only the label.
--
-- SAFETY: the previous row goes to account_reclass_log first; the down restores the old name from it.
-- Re-running is harmless (a renamed row no longer matches). Run
-- supabase/diagnostics/preview_163_rename_duplicate_named_heads.sql first.
-- NO temp tables — the SQL Editor's "Run and enable RLS" splits statements. Use plain "Run".

begin;

create table if not exists public.account_reclass_log (
  id          bigserial primary key,
  migration   text not null,
  society_id  text not null,
  account_id  text not null,
  old_row     jsonb not null,
  logged_at   timestamptz not null default now()
);
alter table public.account_reclass_log enable row level security;
revoke all on public.account_reclass_log from anon, authenticated;

insert into public.account_reclass_log (migration, society_id, account_id, old_row)
select '163', a.society_id::text, a.id, to_jsonb(a)${targets};

update public.accounts a
   set name = v.new_name
  from (values
${valuesBlock()}
  ) as v(id, old_name, type, new_name, ord)
 where a.id = v.id and trim(a.name) = v.old_name and a.type = v.type
   and not exists (select 1 from public.accounts o
                    where o.society_id = a.society_id and o.type = a.type and o.id <> a.id
                      and lower(trim(o.name)) = lower(v.new_name));

insert into public.app_migrations (version, name) values ('163', 'rename_duplicate_named_heads')
  on conflict (version) do nothing;

commit;

notify pgrst, 'reload schema';
`;

  const preview = `-- preview for 163 · READ-ONLY. GENERATED by scripts/gen-migration-163.mjs. Run BEFORE migration 163.
-- One row per account migration 163 will rename. Nothing is written.
select a.society_id::text as society_id, a.id as account_id, a.name as old_name, v.new_name${targets}
 order by a.society_id, v.ord;
`;

  const down = `-- 163 down · put the old names back (from account_reclass_log). The app's own rename (storage.ts) still shows
-- the new name on screen — revert the code as well if that is the intent.
begin;
update public.accounts a
   set name = l.old_row->>'name'
  from public.account_reclass_log l
 where l.migration = '163' and a.society_id::text = l.society_id and a.id = l.account_id;
delete from public.account_reclass_log where migration = '163';
delete from public.app_migrations where version = '163';
commit;
notify pgrst, 'reload schema';
`;
  return {
    'supabase/migrations/163_rename_duplicate_named_heads.sql': migration,
    'supabase/migrations/163_rename_duplicate_named_heads_down.sql': down,
    'supabase/diagnostics/preview_163_rename_duplicate_named_heads.sql': preview,
  };
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  for (const [f, text] of Object.entries(buildFiles())) { writeFileSync(path.join(ROOT, f), text, 'utf8'); console.log('wrote', f); }
}
