// Generates supabase/migrations/114_persist_shared_extra_accounts.sql and its preview FROM the code's own
// ACCOUNTS_TO_ADD list (src/lib/storage.ts), so the SQL can never drift from what the app merges on screen.
//   node scripts/gen-migration-114.mjs          → writes the three files
// test:persist-extra-accounts re-runs buildFiles() and fails if a committed file differs.
import { register } from 'node:module';
import { writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(ROOT, 'src');
register('data:text/javascript,' + encodeURIComponent(`
  import { existsSync } from 'node:fs';
  import { fileURLToPath, pathToFileURL } from 'node:url';
  import { resolve as PR } from 'node:path';
  const SRC = ${JSON.stringify(SRC)};
  export async function resolve(spec, ctx, next) {
    if (spec.startsWith('@/')) { const b = PR(SRC, spec.slice(2)); for (const q of [b + '.ts', b + '.tsx', b + '/index.ts', b]) if (existsSync(q)) return { url: pathToFileURL(q).href, shortCircuit: true }; }
    if (spec.startsWith('.') && !/\\.(ts|tsx|js|mjs|json)$/.test(spec)) { for (const q of [spec + '.ts', spec + '/index.ts']) { const u = new URL(q, ctx.parentURL); if (existsSync(fileURLToPath(u))) return { url: u.href, shortCircuit: true }; } }
    return next(spec, ctx);
  }
`));
const S = await import(pathToFileURL(path.join(SRC, 'lib/storage.ts')).href);

const q = (v) => (v == null ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const b = (v) => (v ? 'true' : 'false');

export function valuesBlock() {
  return S.ACCOUNTS_TO_ADD.map((a, i) =>
    `    (${q(a.id)}, ${q(a.name)}, ${q(a.nameHi)}, ${q(a.type)}, ${q(a.openingBalanceType)}, ${b(a.isSystem)}, ${b(a.isGroup)}, ${q(a.parentId)}, ${q(a.subtype)}, ${i})`
  ).join(',\n');
}

// the rows that would be inserted — the SAME rule as storage.migrateAccounts: skip when the id exists OR the same
// name+type exists; and (database rule) the parent must exist.
const missing = (extra) => `
  from (select distinct society_id from public.accounts) s
 cross join (values
${valuesBlock()}
  ) as v(id, name, "nameHi", type, "openingBalanceType", "isSystem", "isGroup", "parentId", subtype, ord)
 where ${extra}
   and not exists (select 1 from public.accounts a where a.society_id = s.society_id and a.id = v.id)
   and not exists (select 1 from public.accounts a where a.society_id = s.society_id and lower(trim(a.name)) = lower(trim(v.name)) and a.type = v.type)`;

const parentOk = `(v."parentId" is null or exists (select 1 from public.accounts p where p.society_id = s.society_id and p.id = v."parentId"))`;

const insertInto = (cond) => `insert into public.accounts (id, society_id, name, "nameHi", type, "openingBalance", "openingBalanceType", "isSystem", "isGroup", "parentId", subtype, jurisdiction)
select v.id, s.society_id, v.name, v."nameHi", v.type, 0, v."openingBalanceType", v."isSystem", v."isGroup", v."parentId", v.subtype,
       (select a.jurisdiction from public.accounts a where a.society_id = s.society_id and a.jurisdiction is not null limit 1)${missing(cond)}
   and ${parentOk}
on conflict do nothing;`;

export function buildFiles() {
  const migration = `-- 114 · Persist the shared extra accounts (ACCOUNTS_TO_ADD) that existing societies only had ON SCREEN.
-- GENERATED by scripts/gen-migration-114.mjs from the code's own ACCOUNTS_TO_ADD list — do not edit by hand.
--
-- WHY: on every load the app merges ACCOUNTS_TO_ADD (purchase / sales heads 5110-5116 and 4104-4108, Closing Stock
-- 5150, Wages Payable 2109, Overdue Interest Reserve 2211, EPF EDLI 5209, Scheme Income 4300 …) into LOCAL state
-- only — the load path never writes (RM-01). So a society whose chart was seeded before these existed sees a
-- complete chart that its database does not hold, and the server refuses the first voucher on them
-- (post_voucher:account_not_found). Rania 2026-10-07: 16 accounts; 13 of 31 societies, 58 rows.
-- New and reset societies are seeded with the full chart (fullChartForType); this fixes the existing ones.
--
-- WHAT: for every society, add each ACCOUNTS_TO_ADD account it lacks — the SAME rule the app uses on screen: skip when
-- the id already exists OR an account with the same name and type exists; and (database rule) only when its parent
-- group exists. Groups first, then ledgers (so a ledger under a group added in this run finds its parent).
-- Opening balance 0. INSERT only, "on conflict do nothing": no existing row is changed or removed.
-- Run supabase/diagnostics/preview_114_extra_accounts.sql first. Undo: 114_..._down.sql (removes only
-- rows this migration added that nothing references).
-- NO temp tables — the SQL Editor's "Run and enable RLS" splits statements.

begin;

-- 1. groups
${insertInto('v."isGroup"')}

-- 2. ledgers
${insertInto('not v."isGroup"')}

insert into public.app_migrations (version, name) values ('114', 'persist_shared_extra_accounts')
  on conflict (version) do nothing;

commit;

notify pgrst, 'reload schema';
`;

  // preview: a ledger whose parent is a group that this run would also add counts as insertable.
  const preview = `-- preview for 114 · READ-ONLY. GENERATED by scripts/gen-migration-114.mjs. Run BEFORE migration 114.
-- One row per account migration 114 will add, per society. Nothing is written. (Expected on 2026-10-07: 58 rows.)
select s.society_id, v.id as account_id, v.name, case when v."isGroup" then 'group' else 'ledger' end as kind${missing('true')}
   and (v."parentId" is null
        or exists (select 1 from public.accounts p where p.society_id = s.society_id and p.id = v."parentId")
        or (v."parentId" in (${S.ACCOUNTS_TO_ADD.filter((x) => x.isGroup).map((x) => q(x.id)).join(', ')})
            and not exists (select 1 from public.accounts a where a.society_id = s.society_id and a.id = v."parentId")))
 order by s.society_id, v.ord;
`;

  const down = `-- 114 down · remove ONLY the accounts migration 114 added, and only where nothing references them.
-- (Rows are identified by id from ACCOUNTS_TO_ADD with an opening balance of 0 and no postings / links; an account
-- that already has a voucher leg, an opening event or a stock item is kept.)
begin;
delete from public.accounts a
 where a.id in (${S.ACCOUNTS_TO_ADD.map((x) => q(x.id)).join(', ')})
   and coalesce(a."openingBalance", 0) = 0
   and not exists (select 1 from public.voucher_lines l where l.society_id::text = a.society_id::text and l.account_id = a.id)
   and not exists (select 1 from public.voucher_entries l where l.society_id::text = a.society_id::text and l."accountId" = a.id)
   and not exists (select 1 from public.stock_items s where s.society_id::text = a.society_id::text and (s."salesAccountId" = a.id or s."purchaseAccountId" = a.id))
   and not exists (select 1 from public.account_roles r where r.society_id::text = a.society_id::text and r.account_id = a.id)
   and not exists (select 1 from public.accounts c where c.society_id = a.society_id and c."parentId" = a.id);
delete from public.app_migrations where version = '114';
commit;
`;
  return {
    'supabase/migrations/114_persist_shared_extra_accounts.sql': migration,
    'supabase/migrations/114_persist_shared_extra_accounts_down.sql': down,
    'supabase/diagnostics/preview_114_extra_accounts.sql': preview,
  };
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  for (const [f, text] of Object.entries(buildFiles())) { writeFileSync(path.join(ROOT, f), text, 'utf8'); console.log('wrote', f); }
}
